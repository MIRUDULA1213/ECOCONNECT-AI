export function getOneWord(term: string): string {
  const item = ONE_WORD_DEFINITIONS[term];
  return item ? item.word : '';
}

interface WordDefProps {
  term: string;
  value?: string | number | React.ReactNode;
  subtitle?: string;
  size?: 'sm' | 'md' | 'lg';
  className?: string;
  highlightValue?: boolean;
}

export const WordDef: React.FC<WordDefProps> = ({
  term,
  value,
  subtitle,
  size = 'md',
  className = '',
  highlightValue = false,
}) => {
  const def = ONE_WORD_DEFINITIONS[term];
  const word = def?.word;

  return (
    <div className={`space-y-0.5 group relative ${className}`}>
      <div className="flex items-center justify-between gap-1">
        <span className="text-[11px] font-semibold text-slate-400 flex items-center gap-1">
          <span>{term}</span>
          {word && (
            <span
              title={def?.description}
              className="text-[9px] font-mono uppercase tracking-wider text-teal-400 bg-teal-500/10 px-1.5 py-0.2 rounded border border-teal-500/20"
            >
              {word}
            </span>
          )}
        </span>
      </div>

      {value !== undefined && (
        <div
          className={`font-mono font-bold leading-tight ${
            size === 'lg'
              ? 'text-lg sm:text-xl text-white'
              : size === 'md'
              ? 'text-sm text-slate-100'
              : 'text-xs text-slate-200'
          } ${highlightValue ? 'text-teal-400' : ''}`}
        >
          {value}
        </div>
      )}

      {subtitle && <p className="text-[10px] text-slate-500 mt-0.5">{subtitle}</p>}
    </div>
  );
};
